"""Build a GhostFleet scenario file from any Sea Power mission .ini (briefing, objectives, sides). No per-mission code.
python gen_scenario.py "<path to mission .ini>" [-o scenarios/<name>.json]
The winner is NOT derived here: the plugin reports the game's own verdict (/truth mission_status), which the runner uses.
Information policy: the player side gets the mission description, its start message and its objectives; the opposing side gets only a
generic defend-and-engage objective (the mission file gives it no briefing), so neither side sees the other's plan."""
import argparse, json, os, re


def parse_sections(text):
    secs, cur = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            cur = secs.setdefault(line[1:-1], {})
        elif cur is not None and "=" in line:
            k, v = line.split("=", 1)
            cur.setdefault(k.strip(), v.strip())   # first occurrence wins
    return secs


def clean(s):
    s = s.replace("\\n", "\n")
    s = re.sub(r"</?(size|color|b|i)[^>]*>", "", s)
    return re.sub(r"\n{3,}", "\n\n", s).strip()


GENERIC_ROE = ("You are cleared to engage forces that are identified as hostile. Never fire on Neutral or civilian vessels; "
               "avoid civilian casualties. Keep your own units alive: losses count against you.")


def build(text, source=""):
    secs = parse_sections(text)
    lang, mis = secs.get("Language_en", {}), secs["Mission"]
    player, enemy = mis.get("PlayerTaskforce", "Taskforce1"), mis.get("EnemyTaskforce", "Taskforce2")
    idx = lambda tf: int(re.sub(r"\D", "", tf)) - 1          # Taskforce1 -> side index 0 (verified against the live game)
    objs = secs.get(f"{player}_Objectives", {})
    obj_lines = [clean(lang[f"Objective_{k}"]) for k in objs if f"Objective_{k}" in lang]
    start = lang.get(f"{player}StartMessage", "")
    start_body = clean(start.split("|")[1]) if start.count("|") >= 1 else ""
    parts = [clean(lang.get("Description", ""))]
    if start_body:
        parts.append("MISSION BRIEFING:\n" + start_body)
    if obj_lines:
        parts.append("OBJECTIVES:\n" + "\n".join("- " + o for o in obj_lines))
    sides = {
        str(idx(player)): {"role": player + " (player side)", "objective": "\n\n".join(p for p in parts if p), "roe": GENERIC_ROE},
        str(idx(enemy)): {"role": enemy,
                          "objective": "Hostile forces are operating in or near your area. Defend your units and installations and destroy hostile forces that threaten them. "
                                       "You win if the opposing side fails its mission. Your land installations cannot move.",
                          "roe": GENERIC_ROE},
    }
    return {"name": lang.get("Name", os.path.basename(source)), "source_ini": os.path.basename(source), "windows": 12, "step_s": 300, "sides": sides,
            "notes": "generated by gen_scenario.py; winner comes from the game's own mission status"}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("ini"); ap.add_argument("-o", "--out")
    a = ap.parse_args()
    with open(a.ini, encoding="utf-8-sig") as f:
        sc = build(f.read(), a.ini)
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(__file__)), "scenarios", re.sub(r"\W+", "_", sc["name"]).strip("_").lower() + ".json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(sc, f, indent=2, ensure_ascii=False)
    print("wrote", out)
